import io
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from continuity.core import ContinuityError, Store, budget, digest
from continuity.mcp import serve


class ContinuityTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.store = Store(self.root / "archive.sqlite3")
        self.data = [{"id": "room-a", "title": "예제", "messages": [
            {"id": "m1", "role": "user", "content": "배경은 파랑으로 해줘."},
            {"id": "m2", "role": "assistant", "content": "파랑으로 적용하겠습니다."},
            {"id": "m3", "role": "user", "content": "파랑 취소. 최종 배경은 초록. 결제 기능은 보류."}]}]
        self.result = self.do_import(self.data)
        self.snap = self.store.snapshot("demo", ["room-a"], 128)["snapshot"]
        self.session = self.store.new_session(self.snap)["session"]

    def tearDown(self):
        self.store.close()
        self.tmp.cleanup()

    def do_import(self, data, project="demo"):
        file = self.root / "import.json"
        file.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
        return self.store.import_file(project, file)

    def read_all(self, session=None):
        session = session or self.session
        while True:
            chunk = self.store.read_next(session)
            if chunk["done"]:
                break
            self.store.acknowledge(session, chunk["position"], chunk["sha"], chunk["receipt_token"])

    def setup_check(self):
        # Independent operator ground truth, not generated by the reader under test.
        quote = "초록"
        position = self.store.search(self.snap, quote)["matches"][0]["positions"][0]
        self.store.add_checks(self.snap, [{"id": "color", "question": "최종 배경색은?", "expected": "초록",
                                           "position": position, "quote": quote}])
        return position, quote

    def qualify(self, session=None):
        session = session or self.session
        self.read_all(session)
        position, quote = self.setup_check()
        self.store.answer(session, "color", "초록", position, quote)

    def test_original_bytes_roundtrip_and_hash(self):
        out = self.root / "roundtrip.json"
        self.store.export_source(self.result["source_sha256"], out)
        self.assertEqual(out.read_bytes(), (self.root / "import.json").read_bytes())
        self.assertEqual(digest(out.read_bytes()), self.result["source_sha256"])

    def test_export_does_not_overwrite(self):
        path = self.root / "already.txt"
        path.write_text("keep")
        with self.assertRaises(FileExistsError):
            self.store.export_source(self.result["source_sha256"], path)
        self.assertEqual(path.read_text(), "keep")

    def test_full_unicode_reconstruction(self):
        self.assertTrue(self.store.verify(self.snap)["integrity_ok"])
        pieces = [r[0] for r in self.store.db.execute("SELECT body FROM chunks WHERE snapshot=? ORDER BY position", (self.snap,))]
        restored = json.loads("".join(pieces))
        self.assertEqual(restored, self.data[0])

    def test_all_mapping_branches_and_metadata_preserved(self):
        export = {"id": "mapping", "title": "분기", "current_node": "b", "unknown_future_field": {"x": 42},
                  "mapping": {"root": {"parent": None, "message": None, "children": ["a", "b"]},
                              "a": {"parent": "root", "message": {"content": {"parts": ["옛 답변"]}}},
                              "b": {"parent": "root", "message": {"content": {"parts": ["새 답변"]}}}}}
        self.do_import(export, "branches")
        snap = self.store.snapshot("branches", ["mapping"])["snapshot"]
        self.assertEqual(json.loads(self.store.read_chunk(snap, 0)["body"]), export)

    def test_idempotent_import(self):
        self.do_import(self.data)
        self.assertEqual(self.store.db.execute("SELECT COUNT(*) FROM versions").fetchone()[0], 1)
        self.assertEqual(self.store.snapshot("demo", ["room-a"], 128)["snapshot"], self.snap)

    def test_invalid_import_is_atomic(self):
        with self.assertRaises(ContinuityError):
            self.do_import(self.data + [{"id": "bad"}])
        self.assertEqual(len(self.store.list_projects()), 1)

    def test_duplicate_conversation_rejected(self):
        with self.assertRaises(ContinuityError):
            self.do_import(self.data + self.data)

    def test_unknown_order_and_missing_room_rejected(self):
        with self.assertRaises(ContinuityError):
            self.store.snapshot("demo", ["missing"])

    def test_cannot_ack_unread_chunk(self):
        with self.assertRaises(ContinuityError):
            self.store.acknowledge(self.session, 0, "fake", "fake")

    def test_wrong_token_and_digest_rejected(self):
        c = self.store.read_next(self.session)
        for sha, token in [("wrong", c["receipt_token"]), (c["sha"], "wrong")]:
            with self.assertRaises(ContinuityError):
                self.store.acknowledge(self.session, c["position"], sha, token)

    def test_read_retries_return_same_receipt(self):
        a = self.store.read_next(self.session)
        b = self.store.read_next(self.session)
        self.assertEqual(a, b)

    def test_new_ai_session_never_inherits_receipts(self):
        self.read_all()
        fresh = self.store.new_session(self.snap)["session"]
        self.assertEqual(self.store.status(fresh)["chunks_acknowledged"], 0)

    def test_receipts_do_not_imply_comprehension(self):
        self.read_all()
        status = self.store.status(self.session)
        self.assertEqual(status["coverage"], 1)
        self.assertFalse(status["text_handoff_eligible"])
        self.assertFalse(status["perfect_understanding"])

    def test_fabricated_evidence_rejected(self):
        self.read_all()
        with self.assertRaises(ContinuityError):
            self.store.remember(self.session, "fake", "decision", "wrong", [{"position": 0, "quote": "nonexistent"}])

    def test_source_linked_memory_is_append_only(self):
        self.read_all()
        c = self.store.read_chunk(self.snap, 0)
        evidence = [{"position": 0, "quote": c["body"][:20]}]
        self.store.remember(self.session, "one", "uncertain", "검토 필요", evidence)
        self.assertFalse(self.store.memories(self.session)[0].get("semantic_truth_verified", False))
        import sqlite3
        with self.assertRaises(sqlite3.IntegrityError):
            self.store.remember(self.session, "one", "decision", "덮어쓰기", evidence)

    def test_failed_answer_blocks_activation(self):
        self.read_all()
        pos, quote = self.setup_check()
        self.assertFalse(self.store.answer(self.session, "color", "파랑", pos, quote)["passed"])
        with self.assertRaises(ContinuityError):
            self.store.activate(self.session)

    def test_correct_answer_with_wrong_evidence_fails(self):
        pos, _ = self.setup_check()
        self.assertFalse(self.store.answer(self.session, "color", "초록", pos, "파랑")["passed"])

    def test_check_answers_hidden_from_mcp_questions(self):
        self.setup_check()
        self.assertEqual(set(self.store.questions(self.session)[0]), {"id", "question"})

    def test_activation_and_retry_idempotency(self):
        self.qualify()
        self.assertTrue(self.store.activate(self.session)["activated"])
        self.assertTrue(self.store.activate(self.session)["idempotent"])

    def test_new_messages_invalidate_pending_handoff(self):
        self.qualify()
        self.data[0]["messages"].append({"id": "m4", "role": "user", "content": "배경을 다시 검토하자."})
        self.do_import(self.data)
        self.assertTrue(self.store.verify(self.snap)["integrity_ok"])
        self.assertFalse(self.store.status(self.session)["latest_import"])
        with self.assertRaises(ContinuityError):
            self.store.activate(self.session)

    def test_digest_detects_tamper(self):
        with self.store.db:
            self.store.db.execute("UPDATE chunks SET body='tampered' WHERE snapshot=? AND position=0", (self.snap,))
        with self.assertRaises(ContinuityError):
            self.store.verify(self.snap)

    def test_missing_chunk_detected(self):
        with self.store.db:
            self.store.db.execute("DELETE FROM chunks WHERE snapshot=? AND position=0", (self.snap,))
        with self.assertRaises(ContinuityError):
            self.store.verify(self.snap)

    def test_prepare_at_95_percent_is_idempotent(self):
        self.qualify()
        self.store.activate(self.session)
        self.assertFalse(self.store.prepare_handoff(self.session, self.snap, 10000, 9499)["prepared"])
        a = self.store.prepare_handoff(self.session, self.snap, 10000, 9500)
        b = self.store.prepare_handoff(self.session, self.snap, 10000, 9600)
        self.assertEqual(a["target_session"], b["target_session"])
        self.assertFalse(a["native_chat_created"])
        self.assertEqual(self.store.status(a["target_session"])["chunks_acknowledged"], 0)

    def test_stale_predecessor_cannot_replace_new_active(self):
        self.qualify()
        self.store.activate(self.session)
        target = self.store.new_session(self.snap, self.session)["session"]
        rival = self.store.new_session(self.snap, self.session)["session"]
        pos = self.store.search(self.snap, "초록")["matches"][0]["positions"][0]
        for s in (target, rival):
            self.read_all(s)
            self.store.answer(s, "color", "초록", pos, "초록")
        self.store.activate(target)
        with self.assertRaises(ContinuityError):
            self.store.activate(rival)

    def test_cross_project_predecessor_rejected(self):
        self.do_import(self.data, "other")
        snap = self.store.snapshot("other", ["room-a"])["snapshot"]
        with self.assertRaises(ContinuityError):
            self.store.new_session(snap, self.session)

    def test_attachment_reference_blocks_automatic_activation(self):
        self.data[0]["messages"][0]["attachments"] = [{"file_id": "file-unknown"}]
        self.do_import(self.data)
        self.snap = self.store.snapshot("demo", ["room-a"], 128)["snapshot"]
        self.session = self.store.new_session(self.snap)["session"]
        self.qualify()
        with self.assertRaisesRegex(ContinuityError, "Attachment"):
            self.store.activate(self.session)

    def test_asset_bytes_preserved(self):
        path = self.root / "image.bin"
        path.write_bytes(bytes(range(256)))
        asset = self.store.put_asset(path)
        snap = self.store.snapshot("demo", ["room-a"], assets=[{"reference": "image.bin", "sha256": asset["sha256"]}])["snapshot"]
        self.assertEqual(self.store.verify(snap)["asset_count"], 1)

    def test_search_crosses_chunk_boundary(self):
        chunks = list(self.store.db.execute("SELECT body FROM chunks WHERE snapshot=? ORDER BY position", (self.snap,)))
        query = chunks[0]["body"][-5:] + chunks[1]["body"][:5]
        matches = self.store.search(self.snap, query)["matches"]
        self.assertEqual(matches[0]["positions"], [0, 1])

    def test_search_pagination_does_not_skip_same_chunk(self):
        snap = self.store.snapshot("demo", ["room-a"], 8000)["snapshot"]
        all_matches = self.store.search(snap, "파랑")["matches"]
        found = []
        cursor = {}
        while True:
            page = self.store.search(snap, "파랑", limit=1, **cursor)
            found.extend(page["matches"])
            if not page["next_cursor"]:
                break
            cursor = page["next_cursor"]
        self.assertEqual(found, all_matches)

    def test_mcp_lifecycle_and_malformed_input(self):
        requests = [
            {"jsonrpc": "2.0", "id": 1, "method": "tools/list"},
            {"jsonrpc": "2.0", "id": 2, "method": "initialize", "params": {"protocolVersion": "2025-11-25", "clientInfo": {}, "capabilities": {}}},
            {"jsonrpc": "2.0", "method": "notifications/initialized"},
            {"jsonrpc": "2.0", "id": 3, "method": "tools/list"},
            {"jsonrpc": "2.0", "id": 4, "method": "tools/call", "params": {"name": "budget", "arguments": {"context_limit": 1000, "used_tokens": True}}},
            {"jsonrpc": "2.0", "id": 5, "method": "tools/call", "params": {"name": "import_file", "arguments": {}}}]
        sink = io.StringIO()
        serve(self.store, io.StringIO("\n".join(json.dumps(r) for r in requests) + "\n{broken\n"), sink)
        responses = [json.loads(s) for s in sink.getvalue().splitlines()]
        self.assertEqual(responses[0]["error"]["code"], -32002)
        self.assertEqual(responses[1]["result"]["protocolVersion"], "2025-11-25")
        self.assertTrue(responses[2]["result"]["tools"])
        self.assertTrue(responses[3]["result"]["isError"])
        self.assertTrue(responses[4]["result"]["isError"])
        self.assertEqual(responses[5]["error"]["code"], -32700)

    def test_cli_import_and_verify_in_subprocess(self):
        p = subprocess.run([sys.executable, "-m", "continuity", "--db", str(self.root / "cli.db"),
                            "import", "cli", str(self.root / "import.json")], capture_output=True, text=True)
        self.assertEqual(p.returncode, 0, p.stderr)
        self.assertEqual(json.loads(p.stdout)["project"], "cli")

    def test_mcp_stdio_real_subprocess(self):
        messages = [
            {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"protocolVersion": "2025-11-25", "clientInfo": {"name": "smoke", "version": "1"}, "capabilities": {}}},
            {"jsonrpc": "2.0", "method": "notifications/initialized"},
            {"jsonrpc": "2.0", "id": 2, "method": "tools/call", "params": {"name": "budget", "arguments": {"context_limit": 10000, "used_tokens": 9500}}}]
        p = subprocess.run([sys.executable, "-m", "continuity", "--db", str(self.root / "stdio.db"), "mcp"],
                           input="\n".join(json.dumps(m) for m in messages) + "\n",
                           capture_output=True, text=True, encoding="utf-8", timeout=10)
        self.assertEqual(p.returncode, 0, p.stderr)
        output = [json.loads(line) for line in p.stdout.splitlines()]
        self.assertEqual(len(output), 2)
        self.assertTrue(json.loads(output[1]["result"]["content"][0]["text"])["should_prepare_handoff"])


class BudgetTests(unittest.TestCase):
    def test_large_expected_response_triggers_early(self):
        self.assertTrue(budget(10000, 8000, 2500)["should_prepare_handoff"])

    def test_no_overflow_or_negative_capacity(self):
        self.assertEqual(budget(10000, 11000)["remaining_tokens"], 0)
        for values in [(0, 10), (100, -1), (True, 20), (100, 20.5)]:
            with self.assertRaises(ContinuityError):
                budget(*values)


if __name__ == "__main__":
    unittest.main()
